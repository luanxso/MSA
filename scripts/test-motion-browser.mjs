// Verifies user-visible transitions and synchronization without contacting Firebase.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.MSA_PLAYWRIGHT_MODULE||'playwright');
const server=spawn(process.execPath,['scripts/serve-demo.mjs']);
await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);});
let browser;
try {
 browser=await chromium.launch({headless:true,executablePath:process.env.MSA_CHROME_BINARY,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1440,height:1000},timezoneId:'America/Sao_Paulo'}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
 await page.goto('http://127.0.0.1:4173/sistema.html?demonstracao=1&cargo=chefe#producao');
 await page.locator('#ops-tab-content').waitFor();
 assert(await page.evaluate(()=>typeof Motion.animate==='function'),'real Motion library loads locally');
 const entering=await page.evaluate(async()=>{document.querySelector('[data-action="ops-tab"][data-id="apontamentos"]').click();await new Promise(requestAnimationFrame);return Number(getComputedStyle(document.querySelector('#ops-tab-content')).opacity);});
 assert(entering<1,'tab visibly fades into view');
 await page.waitForTimeout(300);
 await page.evaluate(()=>MSA.demo.simulation.advance(1));
 assert.equal(await page.locator('#ops-tab-content').evaluate(el=>el.getAnimations().filter(a=>a.playState==='running').length),0,'live refresh does not replay tab transition');
 // A second message during an outgoing animation must survive the old dismissal.
 await page.evaluate(()=>MSA.operations.notify('Primeira mensagem'));
 await page.locator('#operation-feedback-close').click();
 await page.evaluate(()=>MSA.operations.notify('Segunda mensagem'));
 await page.waitForTimeout(300);
 assert(await page.locator('#operation-feedback').isVisible());
 assert.equal(await page.locator('#operation-feedback-message').innerText(),'Segunda mensagem');
 await page.locator('#operation-feedback-close').click();
 await page.locator('#operation-feedback').waitFor({state:'hidden'});
 await page.evaluate(()=>location.hash='mapa-planta');
 await page.locator('[data-machine="INJ-01"]').click();
 const dialog=page.locator('.plant-machine-dialog');await dialog.waitFor({state:'visible'});
 await page.waitForTimeout(350);
 await page.keyboard.press('Escape');
 assert(await dialog.evaluate(el=>el.open&&el.classList.contains('msa-dialog-closing')),'Escape keeps dialog open for exit animation');
 await dialog.waitFor({state:'hidden'});
 assert(await page.locator('[data-machine="INJ-01"]').evaluate(el=>document.activeElement===el),'focus returns to machine');
 await page.locator('[data-machine="INJ-01"]').click();
 await dialog.locator('[data-plant-action="open-supervisor"]').click();
 await page.locator('.supervisor-heading').waitFor();
 await page.evaluate(()=>{MSA.telemetry.setMode('simulation');MSA.telemetry.scenario('INJ-01','operando');if(MSA.telemetry.paused)MSA.telemetry.pause();});
 await page.waitForTimeout(1200);
 const motion=await page.evaluate(async()=>{
   const el=document.querySelector('[data-line-svg]');
   const offsets=[];for(let i=0;i<8;i++){offsets.push(Number(el.dataset.lineVisualOffset));await new Promise(r=>setTimeout(r,60));}
   return offsets;
 });
 assert(new Set(motion).size>3,'pieces move between one-second data updates');
 await page.locator('[data-plant-action="pause"]').first().click();
 await page.waitForFunction(()=>MSA.telemetry.paused);
 const paused=await page.locator('[data-line-piece]').evaluateAll(ns=>ns.map(n=>n.getAttribute('transform')));
 await page.waitForTimeout(1200);
 assert.deepEqual(await page.locator('[data-line-piece]').evaluateAll(ns=>ns.map(n=>n.getAttribute('transform'))),paused,'pause freezes exactly where pieces are');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.locator('[data-plant-action="pause"]').first().click();
 const reduced=await page.locator('[data-line-piece]').evaluateAll(ns=>ns.map(n=>n.getAttribute('transform')));
 await page.waitForTimeout(1200);
 assert.deepEqual(await page.locator('[data-line-piece]').evaluateAll(ns=>ns.map(n=>n.getAttribute('transform'))),reduced,'reduced motion keeps process artwork stationary');
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.locator('[data-plant-action="back"]').click();
 await page.locator('[data-machine="ABF-01"]').focus();await page.keyboard.press('Enter');
 await dialog.waitFor({state:'visible'});
 await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.sidebar-toggle').click();await page.waitForTimeout(300);
 assert.equal(await page.locator('#sidebar').evaluate(el=>el.inert),false);
 await page.keyboard.press('Escape');await page.waitForTimeout(300);
 assert(await page.locator('.drawer-backdrop').isHidden());
 assert.equal(await page.locator('#workspace').evaluate(el=>el.inert),false);
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('[data-machine="INJ-01"]').click();await page.waitForTimeout(350);
 await mkdir('.qa-motion',{recursive:true});
 await page.screenshot({path:'.qa-motion/dialog-light.png'});
 await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
 await page.locator('[data-theme-toggle]').click();
 await page.locator('[data-machine="INJ-01"]').click();await page.waitForTimeout(350);
 await page.screenshot({path:'.qa-motion/dialog-dark.png'});
 assert.deepEqual(errors,[]);
 console.log('OK: local Motion, tab transitions, live refresh, notification race, Escape/focus, smooth process, pause, reduced motion, mobile drawer and both themes.');
}finally{await browser?.close();server.kill();}
